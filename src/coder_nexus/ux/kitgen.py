def extract(project: Path, brand: Optional[str] = None, font: Optional[str] = None) -> dict:
    """Resolve the design source, keep user decisions/overrides, write design-system.json and kit/."""
    project = project.resolve()
    out_dir = ux_dir(project)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "design-system.json"
    previous = json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}

    system = resolve_design_system(project)
    overrides = dict(previous.get("overrides") or {})
    if brand:
        overrides.setdefault("roles", {})["primary"] = brand
    if font:
        overrides["font"] = font
    for role, value in (overrides.get("roles") or {}).items():
        system["roles"][role] = {"value": value, "from": "user override"}
    if overrides.get("font"):
        system["font"] = {"family": overrides["font"], "files": [], "from": "user override"}
    if overrides:
        system["overrides"] = overrides
    prev_source = previous.get("source") or {}
    if prev_source.get("decision") and prev_source.get("kind") == system["source"]["kind"]:
        system["source"]["decision"] = prev_source["decision"]

    path.write_text(json.dumps(system, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    kit = out_dir / "kit"
    kit.mkdir(parents=True, exist_ok=True)
    shutil.copy2(ASSETS / "kit.js", kit / "kit.js")
    write_kit_css(system, kit)
    write_viewports_js(project)
    write_components_html(system, kit)
    (kit / "README.md").write_text(f"# UX kit\n\n{GENERATED_NOTE}\nOpen `components.html` to see what designs may use.\n", encoding="utf-8")
    return system


# ---------------------------------------------------------------- viewports

def load_viewports(project: Path) -> dict:
    path = ux_dir(project) / "viewports.json"
    if path.is_file():
        return json.loads(path.read_text(encoding="utf-8"))
    return {"schema": 1, "platforms": DEFAULT_VIEWPORTS, "confirmed": False, "decision": None}


def parse_size(text: str) -> tuple[int, int]:
    w, h = text.lower().replace(" ", "").split("x", 1)
    return int(w), int(h)


def save_viewports(project: Path, platforms: dict[str, dict], decision: Optional[str] = None) -> dict:
    data = {
        "schema": 1,
        "platforms": platforms,
        "confirmed": True,
        "decision": decision,
        "updated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    out = ux_dir(project)
    out.mkdir(parents=True, exist_ok=True)
    (out / "viewports.json").write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_viewports_js(project)
    return data
