def ux_dir(project: Path) -> Path:
    return project / ".superpowers" / "ux"


def _font_face(system: dict, kit: Path) -> tuple[str, str]:
    font = system.get("font") or {}
    family = font.get("family") or "Roboto"
    faces = []
    files = font.get("files") or []
    if files:
        (kit / "fonts").mkdir(parents=True, exist_ok=True)
        for f in files:
            src = Path(f["path"])
            if src.is_file():
                shutil.copy2(src, kit / "fonts" / src.name)
                faces.append(
                    f'@font-face {{ font-family: "{family}"; src: url("fonts/{src.name}"); '
                    f'font-weight: {f.get("weight", 400)}; font-style: {f.get("style", "normal")}; }}'
                )
    return family, "\n".join(faces)


def write_kit_css(system: dict, kit: Path) -> None:
    family, faces = _font_face(system, kit)
    roles = system["roles"]
    lines = [f"/* {GENERATED_NOTE} */", f"/* Source: {system['source']['kind']} — {', '.join(system['source'].get('evidence', []))} */", faces, ":root {"]
    for role in ROLES:
        r = roles.get(role)
        if r:
            lines.append(f"  --c-{role}: {r['value']}; /* {r['from']} */")
    for key, val in system.get("geometry", {}).items():
        lines.append(f"  --g-{key}: {val};")
    lines.append(f'  --font: "{family}";')
    lines.append("}")
    lines.append((ASSETS / "base.css").read_text(encoding="utf-8"))
    (kit / "kit.css").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_viewports_js(project: Path) -> Path:
    data = load_viewports(project)
    kit = ux_dir(project) / "kit"
    kit.mkdir(parents=True, exist_ok=True)
    path = kit / "viewports.js"
    path.write_text(f"/* {GENERATED_NOTE} */\nwindow.UX_VIEWPORTS = {json.dumps(data, ensure_ascii=False)};\n", encoding="utf-8")
    return path


